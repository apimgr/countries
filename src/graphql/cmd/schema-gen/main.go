// Command schema-gen writes the GraphQL schema generated from Go annotations.
package main

import (
	"fmt"
	"os"
	"strconv"

	graphqlapi "github.com/apimgr/countries/src/graphql"
)

func main() {
	path := "schema_generated.go"
	schema := graphqlapi.SchemaSDL()
	contents := "// Code generated by go generate; DO NOT EDIT.\n\n// Package graphql contains the generated GraphQL schema.\npackage graphql\n\nconst schemaDefinition = " + strconv.Quote(schema) + "\n"
	if err := os.WriteFile(path, []byte(contents), 0644); err != nil {
		fmt.Fprintln(os.Stderr, "write generated GraphQL schema:", err)
		os.Exit(1)
	}
}
